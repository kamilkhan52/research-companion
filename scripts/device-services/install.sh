#!/bin/bash
# Install (or update, or remove) the launchd agents that keep the phone's dev setup alive on the
# Mac mini: backend, Metro, a watchdog, and a sleep blocker. See README.md beside this file.
#
#   scripts/device-services/install.sh            install or update (idempotent)
#   scripts/device-services/install.sh status     what is loaded and answering
#   scripts/device-services/install.sh uninstall  stop and remove all four agents
#
# The scripts are COPIED out of the repo, so the running services never depend on which branch
# any checkout happens to be on. Re-run after changing them.
#
# Installing restarts the backend, which kills in-flight background jobs (DR-083). It refuses
# while the deploy status reports an active job; pass --force to override.
set -euo pipefail

SRC="$(cd "$(dirname "$0")" && pwd)"
DEST="$HOME/Library/Application Support/research-companion/device-services"
AGENTS="$HOME/Library/LaunchAgents"
LOG_DIR="$HOME/Library/Logs/research-companion"
DOMAIN="gui/$(id -u)"
LABELS="io.scholiast.rc.awake io.scholiast.rc.backend io.scholiast.rc.metro io.scholiast.rc.watchdog"

# The MAIN checkout, even when run from a worktree: the backend must run from the tree deploys
# advance, never from wherever this script was invoked.
REPO="$(cd "$(git -C "$SRC" rev-parse --git-common-dir)/.." && pwd)"
DEVICE="${RC_DEVICE_WORKTREE:-$REPO/.claude/worktrees/device-main}"
PATH_VALUE="/opt/homebrew/bin:/opt/homebrew/sbin:$HOME/.local/bin:/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin"

bootout() { launchctl bootout "$DOMAIN/$1" >/dev/null 2>&1 || true; }

status() {
  local l pid
  for l in $LABELS; do
    if launchctl print "$DOMAIN/$l" >/dev/null 2>&1; then
      pid="$(launchctl print "$DOMAIN/$l" | awk '$1 == "pid" {print $3; exit}')"
      printf '%-28s loaded   pid=%s\n' "$l" "${pid:--}"
    else
      printf '%-28s NOT LOADED\n' "$l"
    fi
  done
  printf 'backend /api/health: '; curl -fsS -m 5 http://127.0.0.1:8000/api/health || echo DOWN; echo
  printf 'metro   /status:     '; curl -fsS -m 5 http://127.0.0.1:8081/status || echo DOWN; echo
  local m; m="$(lsof -nP -t -iTCP:8081 -sTCP:LISTEN 2>/dev/null | head -1)"
  [ -n "$m" ] && echo "metro serves:        $(lsof -a -p "$m" -d cwd -Fn | sed -n 's/^n//p')"
  local a; a="$(pmset -g assertions)"
  if printf '%s' "$a" | grep -q 'PreventSystemSleep named: "caffeinate'; then
    echo "sleep:               blocked by caffeinate"
  else
    echo "sleep:               NOT blocked"
  fi
}

uninstall() {
  local l
  # Watchdog first, or it re-bootstraps the others as they go.
  for l in io.scholiast.rc.watchdog io.scholiast.rc.metro io.scholiast.rc.backend io.scholiast.rc.awake; do
    bootout "$l"; rm -f "$AGENTS/$l.plist"
  done
  echo "removed the agents; scripts and state remain in $DEST"
}

# plist LABEL PROGRAM KEEPALIVE(true|false) [EXTRA_XML]
plist() {
  local label="$1" program="$2" keepalive="$3" extra="${4:-}" name="${1##*.}"
  cat > "$AGENTS/$label.plist" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by research-companion scripts/device-services/install.sh — edit there, not here. -->
<plist version="1.0">
<dict>
  <key>Label</key><string>$label</string>
  <key>ProgramArguments</key>
  <array>$program</array>
  <key>WorkingDirectory</key><string>$HOME</string>
  <key>EnvironmentVariables</key>
  <dict>
    <key>PATH</key><string>$PATH_VALUE</string>
    <key>HOME</key><string>$HOME</string>
    <key>LANG</key><string>en_US.UTF-8</string>
  </dict>
  <key>RunAtLoad</key><true/>
  <key>KeepAlive</key><$keepalive/>
  <key>ThrottleInterval</key><integer>15</integer>
  <key>ProcessType</key><string>Interactive</string>
  <key>SoftResourceLimits</key><dict><key>NumberOfFiles</key><integer>65536</integer></dict>
  <key>HardResourceLimits</key><dict><key>NumberOfFiles</key><integer>65536</integer></dict>
  <key>StandardOutPath</key><string>$LOG_DIR/$name.log</string>
  <key>StandardErrorPath</key><string>$LOG_DIR/$name.log</string>
$extra
</dict>
</plist>
EOF
  plutil -lint -s "$AGENTS/$label.plist"
}

install() {
  local force="${1:-}"
  [ -x "$REPO/run.sh" ] || { echo "no run.sh in $REPO" >&2; exit 1; }
  [ -d "$DEVICE/mobile" ] || { echo "device worktree $DEVICE/mobile is missing" >&2; exit 1; }

  if [ "$force" != "--force" ]; then
    local active
    active="$(curl -fsS -m 10 'http://127.0.0.1:8000/api/devtest/deploy?fetch=false' 2>/dev/null \
      | python3 -c 'import json,sys; d=json.load(sys.stdin)["deploy"]; print(d.get("active_job") or d.get("active_dispatch") or "")' 2>/dev/null || true)"
    if [ -n "$active" ]; then
      echo "a background job is running ($active) — installing restarts the backend and would kill it." >&2
      echo "wait for it, or re-run with --force." >&2
      exit 1
    fi
  fi

  mkdir -p "$DEST/state" "$AGENTS" "$LOG_DIR"
  cp "$SRC"/common.sh "$SRC"/backend.sh "$SRC"/metro.sh "$SRC"/watchdog.sh "$DEST/"
  chmod +x "$DEST"/*.sh
  cat > "$DEST/services.env" <<EOF
RC_REPO="$REPO"
RC_DEVICE_WORKTREE="$DEVICE"
EOF

  # An existing node_modules is taken to match the current lockfile, so installing does not
  # start with a needless multi-minute `npm ci`. If it does not match, delete
  # state/metro-lock.sha and the next Metro start reinstalls.
  if [ ! -f "$DEST/state/metro-lock.sha" ] && [ -x "$DEVICE/mobile/node_modules/.bin/expo" ]; then
    shasum "$DEVICE/mobile/package-lock.json" | cut -d' ' -f1 > "$DEST/state/metro-lock.sha"
  fi

  local l; for l in $LABELS; do bootout "$l"; done

  # -i: no idle sleep; -s: no system sleep on AC power (a Mac mini always is). An asleep Mac is
  # indistinguishable, from the phone, from a crashed server.
  plist io.scholiast.rc.awake \
    "<string>/usr/bin/caffeinate</string><string>-i</string><string>-s</string>" true
  plist io.scholiast.rc.backend "<string>$DEST/backend.sh</string>" true
  plist io.scholiast.rc.metro "<string>$DEST/metro.sh</string>" true
  plist io.scholiast.rc.watchdog "<string>$DEST/watchdog.sh</string>" false \
    "  <key>StartInterval</key><integer>60</integer>"

  date +%s > "$DEST/state/backend.restarted"
  date +%s > "$DEST/state/metro.restarted"
  for l in $LABELS; do launchctl bootstrap "$DOMAIN" "$AGENTS/$l.plist"; done
  echo "installed; logs in $LOG_DIR. Check with: $0 status"
}

case "${1:-install}" in
  install) install "${2:-}" ;;
  --force) install --force ;;
  status) status ;;
  uninstall) uninstall ;;
  *) echo "usage: $0 [install [--force] | status | uninstall]" >&2; exit 2 ;;
esac
